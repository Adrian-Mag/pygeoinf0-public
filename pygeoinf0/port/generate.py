"""Problems generated from profiles: counterparts of graph elements composed into pygeoinf0 objects (plan 020 P5;
experiments/EXP-035-mineral-exploration/GENERATOR.md).

    resolve(ref)                     a counterpart reference: "core:Name" or "core:Name.attr" (a public pygeoinf0 name,
                                     pg.__all__), or "plugin:name/object@version" (an object a registered plugin
                                     declares, at exactly that version). Nothing else resolves: no module paths, no
                                     imports, no eval; inside a module only the names of its __all__ are reachable.
    generate(profile, values=None, coverage=None)
                                     build a profile's objects in order and run its method, if any -> Generated;
                                     coverage: MineralNetwork's coverage report of this profile against its graph (a
                                     dict, or the path of its JSON; ASC-041 P2), attached as checked claims

A profile (the minimal format, until MineralNetwork's schema replaces its outer shape):

    {"profile": id, "graph": {...provenance...},
     "objects": {element id: spec, ...},           built in this order
     "missing": [element ids with no counterpart],  reported, not built (an id, or {element, reason, ...})
     "run": spec}                                   optional: a method, e.g. core:optimisers.gauss_newton
    spec = {"ref": counterpart, "args": [...], "kwargs": {...}, "element": graph element (default: the key)}
    a graph element is an id, {id, instance, proposed, note}, or a list of them (MineralNetwork's counterpart schema,
    ASC-041 P1); fields the generator does not use (kind, note, top-level claims and values) are ignored
    an argument is a plain value, a nested spec, {"$id": an earlier object} or {"$value": a name}

Values (data, numbers, external callables such as a TauP wrapper) come from the experiment, not from the profile:
the profile is structure, what a knowledge graph generates. Each built object that keeps claims gets one, asserted:
"generated by profile P from graph element E (counterpart R)".
"""
import types
from dataclasses import dataclass, field

from ..core.claims import ASSERTED, CHECKED, Claim, Claims
from ..core.errors import GenerationError, Refused


def resolve(ref):
    """The object a counterpart reference names (module docstring)."""
    if not isinstance(ref, str) or ":" not in ref:
        raise Refused(f"a counterpart reference is 'core:Name' or 'plugin:name/object@version', not {ref!r}")
    kind, rest = ref.split(":", 1)
    if kind == "core":
        import pygeoinf0
        head, *attrs = rest.split(".")
        if head not in pygeoinf0.__all__:
            raise Refused(f"{ref}: {head!r} is not a public pygeoinf0 name")
        obj = getattr(pygeoinf0, head)
        for a in attrs:
            if a.startswith("_"):
                raise Refused(f"{ref}: private names do not resolve")
            if isinstance(obj, types.ModuleType) and a not in getattr(obj, "__all__", ()):
                raise Refused(f"{ref}: {a!r} is not in the public names of {obj.__name__}")
            if not hasattr(obj, a):
                raise Refused(f"{ref}: {a!r} does not exist")
            obj = getattr(obj, a)
        if isinstance(obj, types.ModuleType):
            raise Refused(f"{ref} names a module, not an object")
        return obj
    if kind == "plugin":
        target, _, version = rest.partition("@")
        name, _, objname = target.partition("/")
        if not (name and objname and version):
            raise Refused(f"{ref}: a plugin reference is plugin:name/object@version")
        from .plugins import load
        plugin = load(name)
        if plugin.version != version:
            raise Refused(f"{ref}: the plugin {name} installed is version {plugin.version}, the profile pins {version}")
        if objname not in plugin.objects:
            raise Refused(f"{ref}: plugin {name} {version} declares no {objname!r} (it declares {sorted(plugin.objects)})")
        return plugin.objects[objname]
    raise Refused(f"{ref}: unknown counterpart kind {kind!r} (core: or plugin:)")


def element_label(e):
    """A readable label of a graph element: an id, {id, instance, proposed}, a list of them, or a missing-entry dict."""
    if isinstance(e, list):
        return " + ".join(element_label(x) for x in e)
    if isinstance(e, dict):
        if "element" in e and "id" not in e:                       # a 'missing' entry {element, reason, ...}
            return element_label(e["element"]) + (f" ({e['reason']})" if e.get("reason") else "")
        label = str(e.get("id", e))
        if e.get("instance"):
            label += f"[{e['instance']}]"
        return label + (" (proposed)" if e.get("proposed") else "")
    return str(e)


@dataclass
class Generated:
    profile: str
    objects: dict
    result: object = None
    built: list = field(default_factory=list)       # (id, element, ref) in build order
    missing: list = field(default_factory=list)     # elements the profile lists without a counterpart
    graph_coverage: dict = None                     # MineralNetwork's coverage report, when given
    graph_claims: Claims = field(default_factory=Claims)

    def __getitem__(self, key):
        return self.objects[key]

    @property
    def coverage(self):
        return Claims([Claim(f"{len(self.built)} elements built, {len(self.missing)} without a counterpart", ASSERTED,
                             f"profile {self.profile}" + (f"; missing: {'; '.join(map(element_label, self.missing))}"
                                                          if self.missing else ""),
                             key="coverage", holds=not self.missing)])

    def __repr__(self):
        return f"Generated({self.profile}: {', '.join(self.objects)}{'; run' if self.result is not None else ''})"


def generate(profile, values=None, coverage=None):
    """Build a profile's objects and run its method (module docstring)."""
    values = {} if values is None else dict(values)
    pid = profile.get("profile", "profile")
    objects, built = {}, []

    def arg(x, where):
        if isinstance(x, dict):
            if "$id" in x:
                if x["$id"] not in objects:
                    raise GenerationError(f"{pid}/{where}: refers to {x['$id']!r}, which is not built before it")
                return objects[x["$id"]]
            if "$value" in x:
                if x["$value"] not in values:
                    raise GenerationError(f"{pid}/{where}: the experiment supplies no value {x['$value']!r}")
                return values[x["$value"]]
            if "ref" in x:
                return build(x, where, x.get("element", where))
            return {k: arg(v, where) for k, v in x.items()}
        if isinstance(x, (list, tuple)):
            return [arg(v, where) for v in x]
        return x

    def build(spec, where, element):
        ref = spec["ref"]
        target = resolve(ref)
        args, kwargs = arg(spec.get("args", []), where), arg(spec.get("kwargs", {}), where)
        if not callable(target):
            if args or kwargs:
                raise GenerationError(f"{pid}/{where}: {ref} is not callable but has arguments")
            return target
        try:
            obj = target(*args, **kwargs)
        except Exception as e:
            raise GenerationError(f"{pid}/{where}: building graph element {element_label(element)!r} with {ref} failed: "
                                  f"{type(e).__name__}: {e}") from e
        target_claims = getattr(obj, "_claims", None)
        if isinstance(target_claims, list):
            target_claims.append(Claim(f"generated by profile {pid} from graph element {element_label(element)}", ASSERTED,
                                       f"counterpart {ref}", key="generated"))
        return obj

    for key, spec in profile.get("objects", {}).items():
        element = spec.get("element", key)
        objects[key] = build(spec, key, element)
        built.append((key, element, spec["ref"]))
    result = build(profile["run"], "run", "run") if profile.get("run") else None
    out = Generated(pid, objects, result, built, list(profile.get("missing", [])))
    if coverage is not None:
        _attach_coverage(out, coverage)
    return out


def _attach_coverage(out, report):
    """MineralNetwork's coverage report (ASC-041 P2) as checked claims: on the result, and per built object."""
    if not isinstance(report, dict):
        import json
        import pathlib
        report = json.loads(pathlib.Path(report).read_text())
    if report.get("profile") != out.profile:
        raise GenerationError(f"the coverage report is of profile {report.get('profile')!r}, not {out.profile!r}")
    s, graph = report.get("summary", {}), report.get("graph", {}).get("id", "the graph")
    stale = bool(report.get("export", {}).get("stale", False))
    why = (f"MineralNetwork's coverage report against {graph} (export sha256 "
           f"{str(report.get('export', {}).get('sha256', '?'))[:12]}{', STALE' if stale else ''})")
    proposed = s.get("proposed_ids", [])
    out.graph_coverage = report
    out.graph_claims = Claims([Claim(
        f"graph elements: {s.get('exists', 0)} exist, {s.get('proposed', 0)} proposed, {s.get('unknown id', 0)} unknown ids"
        + (f"; proposed: {', '.join(proposed)}" if proposed else ""), CHECKED, why, key="graph coverage",
        holds=not stale and s.get("unknown id", 0) == 0 and s.get("errors", 0) == 0)])
    for entry in report.get("entries", []):
        obj = out.objects.get(entry.get("object"))
        target = getattr(obj, "_claims", None)
        if isinstance(target, list) and entry.get("elements"):
            status = "; ".join(f"{element_label(e)}: {e.get('status')}" for e in entry["elements"])
            target.append(Claim(f"graph status: {status}", CHECKED, why, key="graph status",
                                holds=all(e.get("status") == "exists" for e in entry["elements"])))
