"""The public API as a record (plan 026): every public name with its kind and the first line of its docstring.

    python -m pygeoinf0.api_record > API.md

src/API.md is this text at a release; tests/test_api_record.py fails when the package and the file differ, so a change
of the public API is visible in review and in the next release's changelog.
"""
import importlib
import inspect

# pygeoinf0 first, in the sections of pg.GROUPS (by mathematical role, plan 070 P6); then the subpackages whose names
# are public beyond pg.*, in the order of those groups, and the periphery
MODULES = ("pygeoinf0", "pygeoinf0.sets", "pygeoinf0.spaces", "pygeoinf0.probability", "pygeoinf0.relations",
           "pygeoinf0.inference", "pygeoinf0.properties", "pygeoinf0.meta", "pygeoinf0.optimisers", "pygeoinf0.port",
           "pygeoinf0.functions")


def _kind(obj):
    if inspect.ismodule(obj):
        return "module"
    if inspect.isclass(obj):
        return "class"
    if callable(obj):
        return "function"
    return type(obj).__name__


def _summary(obj):
    if not (inspect.ismodule(obj) or inspect.isclass(obj) or callable(obj)):
        return ""
    doc = inspect.getdoc(obj) or ""
    line = doc.strip().splitlines()[0].strip() if doc.strip() else ""
    return line.replace("|", "\\|")


def _rows(mod, names):
    rows = ["| name | kind | summary |", "|---|---|---|"]
    for n in names:
        obj = getattr(mod, n)
        rows.append(f"| `{n}` | {_kind(obj)} | {_summary(obj)} |")
    return rows


def api_record():
    import pygeoinf0
    out = [f"# The public API of pygeoinf0 {pygeoinf0.__version__}", "",
           ("Generated by `python -m pygeoinf0.api_record` (do not edit by hand): the names each module exports "
           "(`__all__`), their kind and the first line of their docstring."), ""]
    for name in MODULES:
        mod = importlib.import_module(name)
        names = sorted(getattr(mod, "__all__", ()))
        out += [f"## {name} ({len(names)} names)", ""]
        if mod is pygeoinf0:
            out += ["By mathematical role (`pg.GROUPS`): each group opens with its roots and ends with its subpackage. "
                    "Optimisers, port, plotting and catalogue are reached through their subpackages only.", ""]
            for i, (title, group) in enumerate(pygeoinf0.GROUPS, 1):
                out += [f"### {i}. {title} ({len(group)} names)", ""] + _rows(mod, group) + [""]
        else:
            out += _rows(mod, names) + [""]
    return "\n".join(out)


if __name__ == "__main__":
    print(api_record())
