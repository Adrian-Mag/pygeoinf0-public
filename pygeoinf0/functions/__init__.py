"""pygeoinf0.functions: a bank of functions organised by domain (plan 021; experiments/EXP-037-function-bank/DESIGN.md).

Optional: `import pygeoinf0` does not load it.

    import pygeoinf0.functions as F
    f = F.on(B).bump(centre=(0, 0, 0.3), radius=0.2)     # the families that apply to the domain B
    f = F.ball.bump(B, centre=(0, 0, 0.3), radius=0.2)   # the same through the kind's namespace
    f(x, y, z); f.claims; f.integral(); f.normalised(); f.element(M)
    F.catalogue()                                         # families x domain kinds, with summaries
    F.bases.hats(B, 41)                                   # whole bases for pg.Discretisation (bases.py, plan 025)

A bank function is a vectorised callable of Cartesian coordinates with metadata and claims (base.py); M(f) and
f.element(M) check its regularity against the space first (spaces/membership.py). Families are written against
geometry.py and registered in registry.py; families/ holds one module per family group.
"""
import functools
import math
import types

from . import bases, families, geometry
from .base import BankFunction, Regularity, Support
from .registry import KINDS, entries, on_kind


def on(D):
    """The families defined on the kind of D, bound to D."""
    k = geometry.kind(D)
    ns = types.SimpleNamespace()
    for name, e in on_kind(k).items():
        setattr(ns, name, functools.partial(e.builder, D))
    return ns


def _kind_namespace(k):
    ns = types.SimpleNamespace()
    for name, e in on_kind(k).items():
        setattr(ns, name, e.builder)
    return ns


def catalogue():
    """[(family, kinds, summary)] of every registered family."""
    return [(n, e.kinds, e.summary) for n, e in sorted(entries().items())]


def _short(reg):
    o = reg.order
    r = "C^inf" if o == math.inf else "jumps" if o < 0 else f"C^{int(o)}" + (" pw" if reg.piecewise else "")
    return r + (", 0 at bdry" if reg.vanishes_at_boundary is not None else "")


GROUPS = {"smooth": "Bumps and Gaussians", "bands": "Bands", "plateau": "Plateaus", "tapers": "Tapers and radial profiles",
          "wendland": "Compactly supported radial kernels (Wendland, Wu, Buhmann)", "indicators": "Indicators",
          "polynomials": "Polynomials, harmonics and Fourier modes", "eigenfunctions": "Laplacian eigenfunctions",
          "fem": "Finite-element-like functions", "testfields": "Test fields", "curves": "Curves, cylinders and tori"}


def catalogue_table():
    """The catalogue as Markdown (src/FUNCTIONS.md is this text): per family group, each family with its domain
    kinds, and for its first example on each kind's standard domains the regularity, the support and the
    closed forms it carries."""
    groups = {}
    for n, e in sorted(entries().items()):
        groups.setdefault(e.module.rsplit(".", 1)[-1].split("_")[0], []).append((n, e))
    out = ["# The function bank (pygeoinf0.functions)", "",
           ("Generated by `pygeoinf0.functions.catalogue_table()` (`python -m pygeoinf0.functions > FUNCTIONS.md`); "
           "do not edit by hand. Per family: the domain kinds it is defined on and, for its first example on "
           "each kind's first standard domain with one, the regularity (C^inf, C^k, `pw` piecewise, jumps; `0 at bdry`: "
           "vanishes at the boundary), the support (interior, touches the boundary, full) and the closed forms."), "",
           f"{len(entries())} families, {sum(len(e.kinds) for e in entries().values())} (family, domain kind) entries.",
           ""]
    order = list(GROUPS) + sorted(set(groups) - set(GROUPS))
    for g in [g for g in order if g in groups]:
        fams = groups[g]
        out += [f"## {GROUPS.get(g, g)}", "", "| family | kinds | regularity | support | closed forms | summary |",
                "|---|---|---|---|---|---|"]
        for n, e in fams:
            regs, sups, closed = {}, set(), set()
            for k in e.kinds:
                D, params = next((D, ps[0]) for D in geometry.standard(k) for ps in [e.example_params(D)] if ps)
                f = e.builder(D, **params)
                regs.setdefault(_short(f.regularity), []).append(k)
                sups.add(f.support.kind)
                closed |= set(f.closed)
            reg = "; ".join(r if len(regs) == 1 else f"{r} ({', '.join(ks)})" for r, ks in regs.items())
            summary = e.summary.replace("|", "\\|")
            out.append(f"| `{n}` | {', '.join(e.kinds)} | {reg} | {', '.join(sorted(sups))} | "
                       f"{', '.join(sorted(closed)) or '-'} | {summary} |")
        out.append("")
    return "\n".join(out)


